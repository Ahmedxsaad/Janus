# --- legs --------------------------------------------------------------------

LEG_CLUSTER = ["wwwggg", "wwwggg", "wwwggg", "wwwggg", "www...", "www..."]


def leg_frame(
    fore_col: int,
    hind_col: int,
    *,
    lift: str | None = None,
    shorten: str | None = None,
) -> str:
    """Stamp a fore and a hind leg cluster at the given columns.

    ``lift`` raises one cluster ("fore" or "hind") a row and a half off the
    ground, for the paw poses: sniffing, tugging, pointing at a dropped file.

    ``shorten`` truncates one cluster to its top three rows, planted at the
    same spot rather than folded elsewhere. A folded haunch drawn a couple of
    rows below the tail left a one-row gap between the two shapes, which the
    outline pass then rims as two separate pieces: a small fragment floating
    beside the dog rather than a leg tucked under it. Shortening in place is
    guaranteed to meet whatever sits above it, because it is the same column
    that shape was already drawn to meet.
    """
    rows: list[list[str]] = [["." for _ in range(SIZE)] for _ in range(6)]
    for which, col in (("fore", fore_col), ("hind", hind_col)):
        rise = 2 if which == lift else 0
        cluster = LEG_CLUSTER[:3] if which == shorten else LEG_CLUSTER
        for y, cluster_row in enumerate(cluster):
            target = y - rise
            if target < 0:
                continue
            for x, ch in enumerate(cluster_row):
                if ch != "." and 0 <= col + x < SIZE:
                    rows[target][col + x] = ch
    return "\n".join("".join(row) for row in rows)


