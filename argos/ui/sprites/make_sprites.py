def render() -> str:
    """The character file, header and all."""
    parts = [HEADER]
    for name, rows in FRAMES.items():
        parts.append(f"\n# {name}\n" + "\n".join(rows) + "\n")
    return "".join(parts)


def main() -> None:
    """Write the character file, failing loudly if a frame came out malformed."""
    for name, rows in FRAMES.items():
        assert len(rows) == SIZE, f"{name} has {len(rows)} rows"
        for row in rows:
            assert len(row) == SIZE, f"{name} has a row of {len(row)} characters"
    OUT.write_text(render())
    print(f"wrote {len(FRAMES)} frames to {OUT}")


if __name__ == "__main__":
    main()
