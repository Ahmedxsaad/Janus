"""Draw Argos, and write the character file the window reads.

Why a script rather than 24 hand-typed grids
--------------------------------------------
The frames share almost everything: one dog, one silhouette, a handful of parts
that move. Typed out 24 times, a change to the muzzle is 24 edits and the frames
drift apart on the first one somebody misses. Here a pose is a choice of head,
tail and legs, and each part is authored once.

The fills are authored; the outline is not. Every frame gets its dark edge
computed from the shape, which keeps the silhouette even and is the method
the redesign settled on: author the colour, let the script find the border.

Run it from anywhere; it rewrites argos.txt beside itself:

    python argos/ui/sprites/make_sprites.py

argos.txt stays the committed artifact, exactly as icons/icon.png does next to
icons/make_icon.py: the window and the tests read the text, never this file.
"""

from __future__ import annotations

from pathlib import Path

SIZE = 32
OUT = Path(__file__).resolve().parent / "argos.txt"

Frame = list[list[str]]

HEADER = """\
# Argos, 32x32, side profile facing right. German Shepherd: erect pointed
# ears, a long muzzle, a black saddle over a tan coat, a low bushy tail.
#
# GENERATED by make_sprites.py in this directory. Edit the parts there and
# re-run it; editing the rows below by hand is lost on the next run.
#
# One character per pixel:
#   .  transparent          k  outline #160F0A     w  coat #D99347
#   g  coat shade #A96B2C   a  saddle/ears #2A2119  o  saddle shade #15100C
#   b  DataHub blue         d  blue shade          r  red
#
# Red is state, never decoration, and no frame here uses r at all. The collar
# is blue in the art and the renderer is the only thing that turns it red, when
# a finding is live. An open mouth is drawn with the outline colour, because a
# mouth is a hole and a red one made the bark read as an injured dog.
#
# A `# name` line opens a frame and every line after it is a row. Every frame is
# 32 rows of exactly 32 characters, which tests/test_argos.py checks, so a
# mistyped row fails the suite rather than the window.
#
# Legs are two clusters (fore near the chest, hind near the haunch), each a
# near leg ('w') beside a far leg ('g') so the animal reads as four legs rather
# than two. Built from rigid blocks that only ever move as a whole between
# frames, not bent within one: a hand-drawn diagonal reach put pixels next to
# only their diagonal neighbours, and the auto-outline pass (4-directional
# adjacency) then outlined each one on its own, rendering as a trail of
# separate floating squares instead of a limb.
"""


def grid() -> Frame:
    """A blank transparent frame."""
    return [["." for _ in range(SIZE)] for _ in range(SIZE)]


def stamp(target: Frame, art: str, top: int, left: int = 0) -> None:
    """Paint a block of art onto the frame, treating '.' as see-through.

    Left as see-through, rather than opaque, so parts can overlap: the tail is
    drawn under the torso and the head over the shoulder without either having
    to know the other's shape.
    """
    for y, line in enumerate(art.strip("\n").split("\n")):
        for x, char in enumerate(line):
            if char == ".":
                continue
            row, col = top + y, left + x
            if 0 <= row < SIZE and 0 <= col < SIZE:
                target[row][col] = char


def outline(frame: Frame) -> Frame:
    """Grow a one-pixel dark edge around everything solid.

    Orthogonal neighbours only. Including diagonals fattens every corner, and
    at this size the corners are most of the character's shape.
    """
    out = [row[:] for row in frame]
    for y in range(SIZE):
        for x in range(SIZE):
            if frame[y][x] != ".":
                continue
            for dy, dx in ((-1, 0), (1, 0), (0, -1), (0, 1)):
                ny, nx = y + dy, x + dx
                if 0 <= ny < SIZE and 0 <= nx < SIZE and frame[ny][nx] not in ".k":
                    out[y][x] = "k"
                    break
    return out


